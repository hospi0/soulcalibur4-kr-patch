res = {}
for name, jre, kv in T:
    jr = re.compile(jre)
    idx = [r for r in R if jr.search(cl(r['jp']))]
    if not idx: continue
    cnt = collections.OrderedDict((v, []) for v in kv); none = []
    for r in idx:
        k = cl(r['ko']); hit = False
        for v in kv:
            if re.search(v, k): cnt[v].append(r['no']); hit = True
        if not hit: none.append(r['no'])
    res[name] = (len(idx), {v: n for v, n in cnt.items()}, none)
    used = [(v, len(n)) for v, n in cnt.items() if n]
    flag = '◆' if len(used) > 1 else ' '
    print('%s %-24s %4d | %s | 없음 %d' % (flag, name, len(idx), '  '.join('%s %d' % u for u in used), len(none)))
